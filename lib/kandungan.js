for (const k of kandungan) for (const n of k.inci) PETA_INCI.set(n.toLowerCase(), k);

export function bahanDariInci(nama) {
  return PETA_INCI.get(String(nama).toLowerCase()) || null;
}

export function cariBahan(id) {
  return kandungan.find((k) => k.id === id) || null;
}
